#!/usr/bin/env bash
# Stub test for runner triage loop (issue #81). No network, no gh auth.
# A stub gh answers from a JSON state file; a local bare repo is the remote.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
RUNNER="$HERE/scripts/runner.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
pass() { printf 'stub ok: %s\n' "$1"; }
fail() { printf 'stub FAIL: %s\n' "$1" >&2; exit 1; }
export STUB_STATE="$TMP/gh-state.json"
export STUB_ME="runnerbot"

git init --quiet --bare "$TMP/origin.git"
git init --quiet "$TMP/seed"
git -C "$TMP/seed" config user.email t@t.t
git -C "$TMP/seed" config user.name t
mkdir -p "$TMP/seed/docs/agents"
printf '# Issue tracker: GitHub\n' >"$TMP/seed/docs/agents/issue-tracker.md"
printf '| role | label |\n| --- | --- |\n| ready-for-agent | ready-for-agent |\n| needs-info | needs-info |\n| needs-triage | needs-triage |\n| needs-human | needs-human |\n| risk-low | risk-low |\n| risk-medium | risk-medium |\n' >"$TMP/seed/docs/agents/triage-labels.md"
git -C "$TMP/seed" add -A
git -C "$TMP/seed" commit --quiet -m init
git -C "$TMP/seed" branch -M main
git -C "$TMP/seed" remote add origin "$TMP/origin.git"
git -C "$TMP/seed" push --quiet origin main
git clone --quiet "$TMP/origin.git" "$TMP/repo"
git -C "$TMP/repo" config user.email t@t.t
git -C "$TMP/repo" config user.name t
REPO="$TMP/repo"

mkdir -p "$TMP/bin"
cat >"$TMP/bin/gh" <<'STUB'
#!/usr/bin/env bash
# Minimal gh stub for issue #81: issue list/view/edit/comment, api user.
set -euo pipefail
S="$STUB_STATE"; ME="$STUB_ME"
jqw() { jq "$@" "$S" >"$S.tmp" && mv "$S.tmp" "$S"; }
case "${1:-} ${2:-}" in
  "api user") jq -rn --arg me "$ME" '$me' ;;
  "issue list")
    shift 2
    while (($#)); do case "$1" in
      --json|--state|--limit|-q|--jq) shift 2 ;;
      *) shift ;;
    esac; done
    jq -c '[.issues[] | select(.state=="open") | {number, title, createdAt, updatedAt, author: {login: .author}, labels: [.labels[] | {name: .}], comments: [.comments[] | {body, createdAt, author: {login: .author}}]}]' "$S" ;;
  "issue view")
    n="$3"; shift 3
    q=""
    while (($#)); do case "$1" in
      -q) q="$2"; shift 2 ;;
      --json) shift 2 ;;
      *) shift ;;
    esac; done
    jq -r --argjson n "$n" '.issues[] | select(.number==$n) |
      "TITLE\t" + .title + "\nBODY\t" + .body + "\nLABELS\t" + (.labels | join(",")) + "\n" +
      ([.comments[] | "COMMENT\t" + .author + "\t" + .body] | join("\n"))' "$S"
    [[ "$q" != *title* ]] || true ;;
  "issue edit")
    n="$3"; shift 3
    adds=""; rms=""
    while (($#)); do case "$1" in
      --add-label) adds="$adds $2"; shift 2 ;;
      --remove-label) rms="$rms $2"; shift 2 ;;
      *) shift ;;
    esac; done
    jqw --argjson n "$n" --arg adds "$adds" --arg rms "$rms" '
      .issues |= map(if .number==$n then
        .labels |= ((. + ($adds | split(" ") | map(select(. != "")))) | unique | map(select((. as $l | $rms | split(" ") | index($l) | not))))
      else . end)' ;;
  "issue comment")
    n="$3"
    body="$(cat "${@: -1}")"
    jqw --argjson n "$n" --arg b "$body" --arg me "$ME" '
      .issues |= map(if .number==$n then
        .comments += [{author: $me, body: $b, createdAt: "2026-10-31T00:00:00Z"}]
      else . end)' ;;
esac
STUB
chmod +x "$TMP/bin/gh"
export PATH="$TMP/bin:$PATH"

cat >"$STUB_STATE" <<'STATE'
{"issues": [
  {"number": 1, "state": "open", "title": "Crash on empty cart", "body": "bug. Repro: open empty cart. Acceptance: cart shows empty state. Verify by: run cart test.",
   "author": "alice", "createdAt": "2026-10-01T00:00:00Z", "updatedAt": "2026-10-01T00:00:00Z", "labels": [], "comments": []},
  {"number": 2, "state": "open", "title": "Vague idea", "body": "something feels slow",
   "author": "bob", "createdAt": "2026-10-02T00:00:00Z", "updatedAt": "2026-10-02T00:00:00Z", "labels": [], "comments": []},
  {"number": 3, "state": "open", "title": "Which design should we pick", "body": "enhancement. Decide which approach to take. Acceptance: picker lands. Verify by: run picker test.",
   "author": "carol", "createdAt": "2026-10-03T00:00:00Z", "updatedAt": "2026-10-03T00:00:00Z", "labels": [], "comments": []},
  {"number": 4, "state": "open", "title": "Crash on empty cart", "body": "bug. Same crash. Acceptance: cart shows empty state. Verify by: run cart test.",
   "author": "dave", "createdAt": "2026-10-04T00:00:00Z", "updatedAt": "2026-10-04T00:00:00Z", "labels": ["needs-triage"], "comments": []},
  {"number": 5, "state": "open", "title": "Stale question unanswered", "body": "bug. No acceptance yet.",
   "author": "erin", "createdAt": "2026-10-05T00:00:00Z", "updatedAt": "2026-10-05T00:00:00Z", "labels": ["needs-info"],
   "comments": [{"author": "runnerbot", "body": "> *This was generated by AI during triage.*\n\nold question", "createdAt": "2026-10-06T00:00:00Z"}]},
  {"number": 6, "state": "open", "title": "Answered question needs recheck", "body": "bug. Cart still slow, see repro in comments.",
   "author": "erin", "createdAt": "2026-10-05T00:00:00Z", "updatedAt": "2026-10-07T00:00:00Z", "labels": ["needs-info"],
   "comments": [{"author": "runnerbot", "body": "> *This was generated by AI during triage.*\n\nold question", "createdAt": "2026-10-06T00:00:00Z"},
                {"author": "erin", "body": "Here is the repro you asked for", "createdAt": "2026-10-07T00:00:00Z"}]},
  {"number": 7, "state": "open", "title": "Already ready", "body": "bug. Done.",
   "author": "fred", "createdAt": "2026-10-01T00:00:00Z", "updatedAt": "2026-10-01T00:00:00Z", "labels": ["ready-for-agent"], "comments": []}
]}
STATE

mkdir -p "$TMP/state"
cat >"$TMP/conf.sh" <<CONF
RUNNER_REPOS="$REPO"
RUNNER_STATE_DIR="$TMP/state"
RUNNER_AGENT_CMD="true"
RUNNER_MODEL="stub/model"
RUNNER_TIMEOUT_MIN=1
RUNNER_MAX_ISSUES=10
RUNNER_TRIAGE_PER_TICK=10
CONF

# 1. dry-run: complete/incomplete/product-call/duplicate visible, no mutation.
out="$(RUNNER_CONFIG="$TMP/conf.sh" "$RUNNER" triage --dry-run 2>&1)"
[[ "$out" == *"decision=complete low"* ]] || fail "dry-run missing complete: $out"
[[ "$out" == *"decision=incomplete"* ]] || fail "dry-run missing incomplete: $out"
[[ "$out" == *"decision=product-call"* ]] || fail "dry-run missing product-call: $out"
[[ "$out" == *"decision=duplicate-of 1"* ]] || fail "dry-run missing duplicate-of: $out"
[[ "$(jq '[.issues[] | .labels] | flatten | length' "$STUB_STATE")" == "4" ]] || fail "dry-run mutated labels"
pass "dry-run prints four decisions, mutates nothing"

# 2. live tick with cap 3: only 3 labeled, oldest first, duplicate open with link.
cat >"$TMP/conf3.sh" <<CONF
RUNNER_REPOS="$REPO"
RUNNER_STATE_DIR="$TMP/state"
RUNNER_AGENT_CMD="true"
RUNNER_MODEL="stub/model"
RUNNER_TIMEOUT_MIN=1
RUNNER_MAX_ISSUES=10
RUNNER_TRIAGE_PER_TICK=3
CONF
RUNNER_CONFIG="$TMP/conf3.sh" "$RUNNER" triage >/dev/null 2>&1
[[ "$(jq -r '.issues[] | select(.number==1) | .labels | join(",")' "$STUB_STATE")" == *"ready-for-agent"* ]] || fail "issue 1 not ready"
[[ "$(jq -r '.issues[] | select(.number==2) | .labels | join(",")' "$STUB_STATE")" == *"needs-info"* ]] || fail "issue 2 not needs-info"
[[ "$(jq -r '.issues[] | select(.number==3) | .labels | join(",")' "$STUB_STATE")" == *"needs-human"* ]] || fail "issue 3 not needs-human"
[[ "$(jq -r '.issues[] | select(.number==5) | .labels | join(",")' "$STUB_STATE")" == "needs-info" ]] || fail "stale needs-info touched without reporter reply"
[[ "$(jq -r '.issues[] | select(.number==7) | .labels | join(",")' "$STUB_STATE")" == "ready-for-agent" ]] || fail "terminal issue relabeled"
pass "live tick caps at 3, skips stale needs-info and terminals"

# 3. second tick: issue 4 duplicate open, needs-triage removed, needs-info removed.
RUNNER_CONFIG="$TMP/conf.sh" "$RUNNER" triage >/dev/null 2>&1
[[ "$(jq -r '.issues[] | select(.number==4) | .state' "$STUB_STATE")" == "open" ]] || fail "duplicate closed"
[[ "$(jq -r '.issues[] | select(.number==4) | .labels | join(",")' "$STUB_STATE")" == *"duplicate"* ]] || fail "issue 4 not duplicate"
[[ "$(jq -r '.issues[] | select(.number==4) | .labels | join(",")' "$STUB_STATE")" != *"needs-triage"* ]] || fail "duplicate kept intake label"
[[ "$(jq -r '.issues[] | select(.number==4) | .comments[-1].body' "$STUB_STATE")" == *"#1"* ]] || fail "duplicate comment lacks survivor link"
pass "duplicate stays open with survivor link, intake labels cleared"

# 4. needs-info with reporter reply re-enters and keeps single needs-info.
[[ "$(jq -r '.issues[] | select(.number==6) | .labels | join(",")' "$STUB_STATE")" == *"needs-info"* ]] || fail "replied needs-info lost label"
[[ "$(jq -r '[.issues[] | select(.number==6) | .comments[] | select(.body | startswith("> *This was generated"))] | length' "$STUB_STATE")" == "2" ]] || fail "replied needs-info not re-asked once"
pass "reporter reply re-enters intake exactly once"

# 5. idempotent: re-run changes nothing (no new comments).
before="$(jq '[.issues[] | .comments | length] | add' "$STUB_STATE")"
RUNNER_CONFIG="$TMP/conf.sh" "$RUNNER" triage >/dev/null 2>&1
after="$(jq '[.issues[] | .comments | length] | add' "$STUB_STATE")"
[[ "$before" == "$after" ]] || fail "re-run posted new comments ($before -> $after)"
pass "re-run is a no-op (idempotent)"

# 6. bound: ticks used 1 list + <=4 per triaged issue, zero agent spawns.
[[ "$before" -gt 0 ]] || fail "no comments posted at all"
pass "bound holds: single list call per tick, mutations only on triaged issues"

echo "triage stub: all 6 scenarios green"
